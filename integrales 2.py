h = 0.5

def simpson_38_multiple(y, h):
    """Implementación de la Regla de Simpson 3/8 múltiple."""
    n = len(y) - 1
    if n % 3 != 0:
        return "Error: n debe ser múltiplo de 3"
    
    suma = y[0] + y[-1]
    for i in range(1, n):
        if i % 3 == 0:
            suma += 2 * y[i]
        else:
            suma += 3 * y[i]
    
    return (3 * h / 8) * suma


