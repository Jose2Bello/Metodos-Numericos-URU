def cargar_datos(texto):
    """Carga los datos desde el texto proporcionado"""
    lineas = texto.strip().split('\n')
    distancias = []
    presiones = []
    for linea in lineas[1:]:  # Saltar encabezado
        partes = linea.split()
        if len(partes) >= 2:
            distancia = float(partes[0].replace(',', '.'))
            presion = float(partes[1].replace(',', '.'))
            distancias.append(distancia)
            presiones.append(presion)
    return np.array(distancias), np.array(presiones)

