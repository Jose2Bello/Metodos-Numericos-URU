def lagrange_interpolation(x, x_nodes, y_nodes):
    """
    Calcula el valor interpolado en x usando el polinomio de Lagrange
    """
    n = len(x_nodes)
    resultado = 0
    
    for i in range(n):
        termino = y_nodes[i]
        for j in range(n):
            if j != i:
                termino *= (x - x_nodes[j]) / (x_nodes[i] - x_nodes[j])
        resultado += termino
    
    return resultado

# ============================================================================
# MÉTODO DE NEWTON (Diferencias Divididas)
# ============================================================================
def diferencias_divididas(x_nodes, y_nodes):
    """
    Calcula los coeficientes del polinomio de Newton usando diferencias divididas
    """
    n = len(x_nodes)
    tabla = np.zeros((n, n))
    tabla[:, 0] = y_nodes
    
    for j in range(1, n):
        for i in range(n - j):
            tabla[i, j] = (tabla[i+1, j-1] - tabla[i, j-1]) / (x_nodes[i+j] - x_nodes[i])
    
    coeficientes = tabla[0, :]
    return coeficientes

def newton_interpolation(x, x_nodes, coeficientes):
    """
    Evalúa el polinomio de Newton en x
    """
    n = len(coeficientes)
    resultado = coeficientes[0]
    producto = 1
    
    for i in range(1, n):
        producto *= (x - x_nodes[i-1])
        resultado += coeficientes[i] * producto
    
    return resultado

