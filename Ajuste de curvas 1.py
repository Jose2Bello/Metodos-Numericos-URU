# Para un polinomio de grado 2: P(h) = a·h² + b·h + c
# Sistema de ecuaciones normales:
# ΣP = a·Σh² + b·Σh + c·n
# Σ(h·P) = a·Σh³ + b·Σh² + c·Σh
# Σ(h²·P) = a·Σh⁴ + b·Σh³ + c·Σh²

n = len(h)

# Calcular sumatorias necesarias
sum_h = np.sum(h)
sum_h2 = np.sum(h**2)
sum_h3 = np.sum(h**3)
sum_h4 = np.sum(h**4)
sum_P = np.sum(P)
sum_hP = np.sum(h * P)
sum_h2P = np.sum((h**2) * P)

# Construir matriz del sistema de ecuaciones
# [ Σh⁴   Σh³   Σh² ] [a] = [Σh²P]
# [ Σh³   Σh²   Σh  ] [b] = [ΣhP]
# [ Σh²   Σh    n   ] [c] = [ΣP]

